import {chromium} from "playwright";
import {mkdir,readFile} from "node:fs/promises";
import path from "node:path";
const output=path.resolve("out");await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:1512,height:990},acceptDownloads:true});
const errors=[];page.on("pageerror",e=>errors.push(e.message));
try{
 const res=await page.goto("http://127.0.0.1:8000/brand-center/production-studio/index.html",{waitUntil:"domcontentloaded"});
 if(!res?.ok())throw new Error("Wizard não carregou");
 await page.locator("#sceneOverview span").first().waitFor();
 if((await page.locator("#sceneOverview span").count())!==8)throw new Error("Filme precisa de oito cenas.");
 if((await page.locator("iframe[src*='github.com']").count())!==0)throw new Error("Prévia bloqueada do GitHub ainda presente.");
 if((await page.locator("[data-panel='0']").isHidden()))throw new Error("A primeira tela precisa ser Motion.");
 await page.screenshot({path:path.join(output,"production-01-motion-desktop.png"),fullPage:true});
 await page.locator("[data-format='vertical']").click();
 if(!String(await page.locator("#summaryFormat").textContent()).includes("9:16"))throw new Error("Formato vertical não refletiu no resumo.");
 await page.locator("#next").click();
 if((await page.locator("[data-panel='1']").isHidden()))throw new Error("Narração não abriu.");
 if((await page.locator("#voiceScene option").count())!==8)throw new Error("Roteiro incompleto");
 const [json]=await Promise.all([page.waitForEvent("download"),page.locator("#downloadVoice").click()]);
 const file=path.join(output,"voice-wizard.json");await json.saveAs(file);
 if(JSON.parse(await readFile(file,"utf8")).scenes.length!==8)throw new Error("Download roteiro incorreto");
 await page.screenshot({path:path.join(output,"production-02-narration-desktop.png"),fullPage:true});
 await page.locator("#next").click();
 if((await page.locator("[data-panel='2']").isHidden()))throw new Error("Sons não abriu.");
 if((await page.locator("#effects>div").count())!==9)throw new Error("Catálogo de efeitos incompleto.");
 await page.locator("#musicVolume").fill("0.12");
 await page.locator("#sfxEnabled").uncheck();
 if(!String(await page.locator("#summarySfx").textContent()).includes("Desativados"))throw new Error("Efeitos não foram desativados.");
 await page.screenshot({path:path.join(output,"production-03-sounds-desktop.png"),fullPage:true});
 await page.locator("#next").click();
 if((await page.locator("[data-panel='3']").isHidden()))throw new Error("Finalizar não abriu.");
 if(!(await page.locator("#downloadVideo").isDisabled()))throw new Error("Download nunca deve aparecer pronto sem arquivo.");
 const instructions=await page.locator("#instructions").textContent();
 if(!instructions.includes("--format=vertical")||!instructions.includes("--sfx=off")||!instructions.includes("--music-volume=0.12"))throw new Error("Comandos não respeitam escolhas.");
 await page.screenshot({path:path.join(output,"production-04-finish-desktop.png"),fullPage:true});
 await page.locator("[data-go='1']").click();
 await page.locator('input[value="silent"]').check();
 await page.locator("[data-go='3']").click();
 if(!(await page.locator("#instructions").textContent()).includes("--mode=silent"))throw new Error("Sem narração deve usar render silent com música.");
 const shell=await browser.newPage({viewport:{width:1440,height:900}});
 await shell.goto("http://127.0.0.1:8000/brand-center/",{waitUntil:"domcontentloaded"});
 await shell.locator('button[data-doc="motion-production"]').click();
 await shell.waitForFunction(()=>document.getElementById("frame").getAttribute("src")==="production-studio/index.html");
 const inner=await shell.locator("#frame").elementHandle();
 const frame=await inner.contentFrame();
 if(!frame)throw new Error("Wizard não foi carregado dentro do Brand Center");
 await frame.locator("#motionTitle").waitFor();
 const mobile=await browser.newPage({viewport:{width:390,height:844}});
 await mobile.goto("http://127.0.0.1:8000/brand-center/production-studio/index.html",{waitUntil:"domcontentloaded"});
 await mobile.locator("#sceneOverview span").first().waitFor();
 await mobile.screenshot({path:path.join(output,"production-01-motion-mobile.png"),fullPage:true});
 await mobile.locator("[data-go='2']").click();
 await mobile.screenshot({path:path.join(output,"production-03-sounds-mobile.png"),fullPage:true});
 if(errors.length)throw new Error("Erros JS: "+errors.join("; "));
 console.log("PASS: wizard 4 etapas, 8 cenas, 9 efeitos, formato, voz, som, MP4 condicional e responsividade");
}finally{await browser.close();}
